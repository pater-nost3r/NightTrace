export const DICTS = { ru, en };
export const FULL = ["ru", "en"];
// Languages offered before (SkyShift) — kept, but honestly labelled as browser translation.
export const AUTO = ["es", "de", "fr", "it", "pt", "pl", "uk", "tr", "ja", "ko", "zh", "ar", "he", "hi"];

let lang = "ru";
export const getLang = () => lang;
export const uiLang = () => (FULL.includes(lang) ? lang : "en");
export function setLang(code) { lang = FULL.includes(code) || AUTO.includes(code) ? code : "ru"; }

export function t(key, vars) {
  const dict = DICTS[uiLang()];
  let s = dict[key] ?? DICTS.ru[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
  return s;
}

// Number formatting with the UI locale (decimal comma in Russian).
export function num(v, digits = 2) {
  if (v === null || v === undefined || !Number.isFinite(v)) return t("misc.unknown");
  return new Intl.NumberFormat(uiLang() === "ru" ? "ru-RU" : "en-GB", { minimumFractionDigits: digits, maximumFractionDigits: digits }).format(v);
}
export const pct = (v) => (Number.isFinite(v) ? new Intl.NumberFormat(uiLang() === "ru" ? "ru-RU" : "en-GB", { style: "percent", maximumFractionDigits: v < 0.01 && v > 0 ? 2 : 0 }).format(v) : t("misc.unknown"));

export function duration(sec) {
  if (!Number.isFinite(sec)) return t("misc.unknown");
  const s = Math.abs(sec);
  if (s < 600) return `${Math.round(s)} ${t("unit.s")}`;
  if (s < 2 * 86400) return `${Math.floor(s / 3600)} ${t("unit.h")} ${Math.round((s % 3600) / 60)} ${t("unit.min")}`;
  const d = s / 86400;
  if (d < 60) return `${num(d, d < 10 ? 1 : 0)} ${t("unit.d")}`;
  return `${num(d, 0)} ${t("unit.d")} (≈ ${num(d / 30.44, 0)} ${t("unit.mo")})`;
}

export function dateUTC(iso, withTime = true) {
  const d = new Date(iso);
  if (isNaN(d)) return "—";
  const p = (n) => String(n).padStart(2, "0");
  const date = `${d.getUTCFullYear()}-${p(d.getUTCMonth() + 1)}-${p(d.getUTCDate())}`;
  return withTime ? `${date} ${p(d.getUTCHours())}:${p(d.getUTCMinutes())}:${p(d.getUTCSeconds())}` : date;
}
